package prisons.solar.npclib.api.entity;

/**
 * Broad categories of entity types.
 */
public enum EntityCategory {
    /**
     * Player entities (fake players with skins).
     */
    PLAYER,

    /**
     * Mob entities (living creatures).
     */
    MOB,

    /**
     * Display entities (text, block, item displays).
     */
    DISPLAY,

    /**
     * Object entities (armor stands, item frames, etc).
     */
    OBJECT
}
